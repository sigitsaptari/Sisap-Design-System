#!/usr/bin/env node
/**
 * SisapDS Token Build Tool.
 *
 * Reads W3C DTCG token files from tokens/base, tokens/semantic, and tokens/component,
 * resolves {alias} references, and generates:
 *   - tokens/build/tokens.css (:root + [data-theme="dark"])
 *   - tokens/build/tailwind-theme.css (Tailwind CSS v4 @theme inline)
 */
import { readFileSync, writeFileSync, mkdirSync, readdirSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");

const readJson = (path) => JSON.parse(readFileSync(path, "utf8"));

const readDirJson = (dir) => {
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => f.endsWith(".json"))
    .sort()
    .map((f) => readJson(join(dir, f)));
};

/** Flatten a DTCG object into { "path.to.token": node } where node carries $value. */
function flatten(obj, prefix = "", out = {}) {
  for (const [key, value] of Object.entries(obj)) {
    const path = prefix ? `${prefix}.${key}` : key;
    if (value && typeof value === "object" && !Array.isArray(value)) {
      if ("$value" in value) {
        out[path] = value;
      } else {
        flatten(value, path, out);
      }
    }
  }
  return out;
}

const mergeFlattened = (...sets) => Object.assign({}, ...sets);

/** Resolve one (possibly aliased) token value; detects circular references. */
function resolveValue(path, tokens, stack = new Set()) {
  if (stack.has(path)) {
    throw new Error(`Circular token reference involving "${path}"`);
  }
  stack.add(path);
  const node = tokens[path];
  if (!node) {
    throw new Error(`Unknown token reference "{${path}}"`);
  }
  return substitute(String(node.$value), tokens, stack);
}

function substitute(value, tokens, stack) {
  return value.replace(/\{([^{}]+)\}/g, (_, ref) =>
    resolveValue(ref.trim(), tokens, new Set(stack))
  );
}

const kebab = (s) =>
  s
    .replace(/[()]+/g, "")
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/[\s_]+/g, "-")
    .replace(/\./g, "-")
    .replace(/--+/g, "-")
    .toLowerCase();

// 1. Base Primitives
const baseTokens = mergeFlattened(
  ...readDirJson(join(repoRoot, "tokens/base")).map((json) => flatten(json))
);

// 2. Component Tokens
const componentTokens = mergeFlattened(
  ...readDirJson(join(repoRoot, "tokens/component")).map((json) => flatten(json))
);

// 3. Semantic Tokens (Light & Dark)
const semanticDir = join(repoRoot, "tokens/semantic");
const lightFile = join(semanticDir, "light.json");
const darkFile = join(semanticDir, "dark.json");

const lightJson = existsSync(lightFile) ? readJson(lightFile) : {};
const darkJson = existsSync(darkFile) ? readJson(darkFile) : {};

const lightTokens = mergeFlattened(baseTokens, flatten(lightJson), componentTokens);
const darkTokens = mergeFlattened(baseTokens, flatten(darkJson), componentTokens);

// Resolve values
const resolvedBase = {};
for (const [key, node] of Object.entries(baseTokens)) {
  resolvedBase[key] = resolveValue(key, baseTokens);
}

const resolvedLight = {};
for (const [key, node] of Object.entries(lightTokens)) {
  resolvedLight[key] = resolveValue(key, lightTokens);
}

const resolvedDark = {};
for (const [key, node] of Object.entries(darkTokens)) {
  resolvedDark[key] = resolveValue(key, darkTokens);
}

const weightMap = {
  regular: "400",
  "regular-italic": "400",
  medium: "500",
  "medium-italic": "500",
  semibold: "600",
  "semibold-italic": "600",
  bold: "700",
  "bold-italic": "700",
};

const cleanKey = (key) =>
  kebab(key)
    .replace(/^radius-radius-/, "radius-")
    .replace(/^spacing-spacing-/, "spacing-")
    .replace(/^font-family-font-family-/, "font-family-");

// Generate tokens.css
const cssLines = [
  "/**",
  " * AUTO-GENERATED - DO NOT EDIT MANUALLY",
  " * Generated by scripts/build-tokens.mjs",
  " */",
  "",
  ":root {"
];

// Base & Light tokens in :root
for (const [key, val] of Object.entries(resolvedLight)) {
  let finalVal = val;
  if (key.startsWith("fontWeight.")) {
    const wKey = kebab(key.replace("fontWeight.", ""));
    if (weightMap[wKey]) finalVal = weightMap[wKey];
  }
  const cleanName = cleanKey(key);
  const rawName = kebab(key);
  cssLines.push(`  --ds-${cleanName}: ${finalVal};`);
  if (cleanName !== rawName) {
    cssLines.push(`  --ds-${rawName}: var(--ds-${cleanName});`);
  }
}
cssLines.push("}");
cssLines.push("");

// Dark theme overrides in [data-theme="dark"]
cssLines.push('[data-theme="dark"] {');
for (const [key, val] of Object.entries(resolvedDark)) {
  if (resolvedLight[key] !== val) {
    let finalVal = val;
    if (key.startsWith("fontWeight.")) {
      const wKey = kebab(key.replace("fontWeight.", ""));
      if (weightMap[wKey]) finalVal = weightMap[wKey];
    }
    const cleanName = cleanKey(key);
    const rawName = kebab(key);
    cssLines.push(`  --ds-${cleanName}: ${finalVal};`);
    if (cleanName !== rawName) {
      cssLines.push(`  --ds-${rawName}: var(--ds-${cleanName});`);
    }
  }
}
cssLines.push("}");
cssLines.push("");

// Ripple click feedback animation (tiket.com style)
cssLines.push("/* Ripple click wave animation (tiket.com style) */");
cssLines.push("@keyframes ds-ripple {");
cssLines.push("  0% {");
cssLines.push("    transform: scale(0);");
cssLines.push("    opacity: 0.40;");
cssLines.push("  }");
cssLines.push("  50% {");
cssLines.push("    opacity: 0.32;");
cssLines.push("  }");
cssLines.push("  100% {");
cssLines.push("    transform: scale(1);");
cssLines.push("    opacity: 0;");
cssLines.push("  }");
cssLines.push("}");
cssLines.push("");
cssLines.push(".animate-ds-ripple {");
cssLines.push("  animation: ds-ripple 1200ms cubic-bezier(0.2, 0.8, 0.25, 1) forwards;");
cssLines.push("}");
cssLines.push("");

// Generate tailwind-theme.css (for Tailwind CSS v4 @theme inline)
const twLines = [
  "/**",
  " * AUTO-GENERATED - DO NOT EDIT MANUALLY",
  " * Tailwind CSS v4 Theme Mapping",
  " */",
  "",
  "@theme inline {"
];

for (const key of Object.keys(resolvedLight)) {
  const cleanVar = `--ds-${cleanKey(key)}`;
  if (key.startsWith("color.") || key.startsWith("semantic.color.") || key.startsWith("component.")) {
    twLines.push(`  --color-${kebab(key)}: var(${cleanVar});`);
  } else if (key.startsWith("spacing.")) {
    const name = kebab(key.replace("spacing.", ""));
    const clean = name.replace(/^spacing-/, "");
    // Layout protection: DO NOT emit bare --spacing-sm, --spacing-md, --spacing-lg, --spacing-xl
    // because in Tailwind v4 they hijack max-w-sm, max-w-md, max-w-lg, w-lg to 8px-16px!
    const isNamedSize = ["none", "xxs", "xs", "sm", "md", "lg", "xl", "2xl", "3xl", "4xl", "5xl", "6xl", "7xl", "8xl", "9xl", "10xl", "11xl"].includes(clean);
    if (!isNamedSize) {
      twLines.push(`  --spacing-${clean}: var(${cleanVar});`);
    } else {
      twLines.push(`  --spacing-spacing-${clean}: var(${cleanVar});`);
    }
  } else if (key.startsWith("radius.")) {
    const name = kebab(key.replace("radius.", ""));
    const clean = name.replace(/^radius-/, "");
    twLines.push(`  --radius-${clean}: var(${cleanVar});`);
  } else if (key.startsWith("fontSize.")) {
    const name = kebab(key.replace("fontSize.", ""));
    const clean = name.replace(/^text-/, "");
    const lineVar = `--ds-${cleanKey(key.replace("fontSize.", "lineHeight."))}`;
    twLines.push(`  --text-${clean}: var(${cleanVar});`);
    twLines.push(`  --text-${clean}--line-height: var(${lineVar});`);
  } else if (key.startsWith("lineHeight.")) {
    const name = kebab(key.replace("lineHeight.", ""));
    const clean = name.replace(/^text-/, "");
    twLines.push(`  --leading-${clean}: var(${cleanVar});`);
  } else if (key.startsWith("fontWeight.")) {
    const name = kebab(key.replace("fontWeight.", ""));
    const num = weightMap[name] || "400";
    twLines.push(`  --font-weight-${name}: ${num};`);
  } else if (key.startsWith("shadow.")) {
    const name = kebab(key.replace("shadow.", ""));
    twLines.push(`  --shadow-${name}: var(${cleanVar});`);
  } else if (key.startsWith("blur.")) {
    const name = kebab(key.replace("blur.", ""));
    twLines.push(`  --blur-${name}: var(${cleanVar});`);
  }
}
twLines.push("}");
twLines.push("");

// Ensure output directory exists
const outDir = join(repoRoot, "tokens/build");
mkdirSync(outDir, { recursive: true });

writeFileSync(join(outDir, "tokens.css"), cssLines.join("\n"), "utf8");
writeFileSync(join(outDir, "tailwind-theme.css"), twLines.join("\n"), "utf8");

console.log(" Tokens successfully built in tokens/build/ (tokens.css & tailwind-theme.css)");
